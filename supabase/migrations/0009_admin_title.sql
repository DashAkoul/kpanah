--  «لقب» برای مدیران: یک برچسب کوتاه (مثل «پشتیبانی فروش» یا «مدیر محتوا»)
--  تا در تاریخچهٔ پیام‌ها/تیکت‌ها معلوم باشد کدام مدیر چه کاری انجام داده.
-- ═══════════════════════════════════════════════════════════════════════

alter table public.users
  add column if not exists admin_title text;

comment on column public.users.admin_title is
  'لقب اختیاری مدیر — در پنل ادمین و تاریخچهٔ پیام‌ها نمایش داده می‌شود.';
